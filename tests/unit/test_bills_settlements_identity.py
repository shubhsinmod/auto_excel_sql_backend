def test_bills_autogenerated_identity_and_settlements_fk(bills_settlements_schema):
    """
    Verifies:
    1. Bills.BillNo receives an autogenerated DB identity (e.g. 1), NOT the invoice number.
    2. Bills.Bill_Number receives the Excel invoice number (e.g. 98765).
    3. Settlements.BillNo receives the autogenerated Bills.BillNo (1), NOT the invoice number.
    4. Settlements.Outlet_ID and Bills.Outlet_ID receive the resolved Outlet_ID from normalized name ('  OLD  madras  road  ' -> 5).
    """
    engine = create_engine("sqlite:///:memory:")
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE Outlets (Outlet_ID INTEGER PRIMARY KEY AUTOINCREMENT, Outlet_Name TEXT)"))
        conn.execute(text("""
            CREATE TABLE Bills (
                BillNo INTEGER PRIMARY KEY AUTOINCREMENT,
                Bill_Number INTEGER NOT NULL,
                Bill_Date TEXT NOT NULL,
                Bill_Amount REAL,
                Outlet_ID INTEGER
            )
        """))
        conn.execute(text("""
            CREATE TABLE Settlements (
                Settlement_ID INTEGER PRIMARY KEY AUTOINCREMENT,
                BillNo INTEGER NOT NULL,
                Outlet_ID INTEGER,
                Settlement_Type TEXT,
                Cash REAL,
                Total REAL
            )
        """))
        # Seed outlet ID 5: 'OLD madras road'
        conn.execute(text("INSERT INTO Outlets (Outlet_ID, Outlet_Name) VALUES (5, 'OLD madras road')"))

    # Excel row has messy case and spacing for outlet, plus invoice number 98765
    df = pd.DataFrame([
        {
            "Invoice_No": 98765,
            "Date": "2026-07-10 12:00:00",
            "Amount": 450.0,
            "restaurant_name": "  oLd   mAdRaS   RoAd  ",
            "Total": 450.0
        }
    ])

    mappings = [
        ColumnMappingResult(excelColumn="Invoice_No", databaseTable="Bills", databaseColumn="Bill_Number", status="MATCHED"),
        ColumnMappingResult(excelColumn="Date", databaseTable="Bills", databaseColumn="Bill_Date", status="MATCHED"),
        ColumnMappingResult(excelColumn="Amount", databaseTable="Bills", databaseColumn="Bill_Amount", status="MATCHED"),
        ColumnMappingResult(excelColumn="restaurant_name", databaseTable="Outlets", databaseColumn="Outlet_Name", status="MATCHED"),
        ColumnMappingResult(excelColumn="Total", databaseTable="Settlements", databaseColumn="Total", status="MATCHED"),
    ]

    with patch("app.services.excel_service.excel_service.get_upload_session") as mock_session, \
         patch("app.migration.engine.get_engine", return_value=engine), \
         patch("app.services.database_service.database_service.get_schema_metadata", return_value=bills_settlements_schema), \
         patch("app.migration.engine.load_file_dataframe", return_value=df), \
         patch("app.migration.engine.pd.io.common.file_exists", return_value=True), \
         patch("app.mapping.matcher.ColumnMatcher.match_columns", return_value=mappings), \
         patch("os.path.exists", return_value=True):

        mock_session.return_value = {"filePath": "dummy.xlsx", "sheetName": None, "headerRowNumber": 1}
        res = MigrationEngine.execute_migration("upload_test_bills_settlements_identity")

    assert res.status == "COMPLETED"
    assert res.transactionStatus == "COMMITTED"

    with engine.connect() as conn:
        bills = conn.execute(text("SELECT BillNo, Bill_Number, Outlet_ID, Bill_Amount FROM Bills")).fetchall()
        assert len(bills) == 1
        bill_row = bills[0]
        # Bills.BillNo is 1 (autogenerated by SQLite AUTOINCREMENT)
        assert bill_row[0] == 1
        # Bills.Bill_Number is 98765 (from Invoice_No)
        assert bill_row[1] == 98765
        # Bills.Outlet_ID resolved to 5 from normalized '  oLd   mAdRaS   RoAd  '
        assert bill_row[2] == 5

        settlements = conn.execute(text("SELECT Settlement_ID, BillNo, Outlet_ID, Total FROM Settlements")).fetchall()
        assert len(settlements) == 1
        settlement_row = settlements[0]
        # Settlements.BillNo MUST be the generated Bills.BillNo (1), NOT the invoice number 98765!
        assert settlement_row[1] == 1
        # Settlements.Outlet_ID MUST be resolved from cached Outlets (5)
        assert settlement_row[2] == 5
        assert settlement_row[3] == 450.0
